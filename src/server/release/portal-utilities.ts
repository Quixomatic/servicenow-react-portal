import { gs } from '@servicenow/glide';
import { GR, getById, findOne, str } from '../lib/gr.ts';
import { T } from '../lib/tables.ts';
import { sha256, parseJson, nowValue } from '../lib/util.ts';
import { assetUrl, CANDIDATES_ASSET } from '../registry/registry.ts';
import { compilePortalUtilities, COMPILER_VERSION } from '../compiler/compiler.ts';
import { HOST_CANDIDATES } from '../compiler/host-candidates.ts';
import { flattenRegions } from '../runtime/portal-service.ts';
import type { Manifest } from '../runtime/portal-service.ts';
import type { BuildRef, ComponentRef, PortalUtilities } from '../../shared/contracts';

/**
 * One Tailwind utilities sheet per portal (.plans/backlog.md F3, option 2).
 *
 * Every component build stores its valid Tailwind candidates (tailwind-candidates.json). At
 * reprocess, the candidates of every build in the portal's manifest (layouts, placements, their
 * transitive imports) plus the host's classes (host-candidates.ts, generated by the host's build:css)
 * are unioned and hashed. An unchanged hash reuses the release's sheet; a changed one compiles the
 * union once, at the end of the current script, then reprocesses the portal again so the manifest
 * points at the new sheet.
 *
 * Until then the manifest keeps the previous sheet, covering only the builds whose utilities did not
 * change (their keys are content hashes); everything else falls back to its own utilities sheet.
 */

export const PORTAL_UTILITIES_ASSET = 'portal-utilities.css';

export interface UtilitiesPlan {
    hash: string;
    candidates: string[];
    covers: string[];
    builds: number;
}

/** Every build of a manifest: layouts, placements (nested blocks included) and their imports. */
function manifestBuilds(m: Manifest): BuildRef[] {
    const out: BuildRef[] = [];
    const seen: Record<string, boolean> = {};
    const add = (b: BuildRef | null | undefined) => {
        if (!b || !b.id) return;
        const key = b.id + '|' + (b.utilitiesKey || '');
        if (seen[key]) return;
        seen[key] = true;
        out.push(b);
    };
    const addRef = (ref: ComponentRef | null | undefined) => {
        if (!ref) return;
        add(ref.build);
        for (const imp of ref.imports || []) add(imp.build);
    };
    for (const id of Object.keys(m.layouts)) addRef(m.layouts[id]);
    for (const pl of flattenRegions(m.regions)) addRef(pl.component);
    for (const page of m.pages) for (const pl of flattenRegions(page.regions)) addRef(pl.component);
    return out;
}

/** The union of a manifest's candidates (plus the host's), its hash and the keys it covers. */
export function planUtilities(m: Manifest): UtilitiesPlan {
    const union: Record<string, boolean> = {};
    for (const c of HOST_CANDIDATES) union[c] = true;
    const covers: Record<string, boolean> = {};
    let builds = 0;
    for (const b of manifestBuilds(m)) {
        if (!b.utilitiesKey) continue;
        const asset = findOne(T.buildAsset, `build=${b.id}^path=${CANDIDATES_ASSET}`);
        if (!asset) continue;
        const list = parseJson<string[]>(str(asset, 'content'), []);
        if (!Array.isArray(list)) continue;
        for (const c of list) union[c] = true;
        covers[b.utilitiesKey] = true;
        builds++;
    }
    const candidates = Object.keys(union).sort();
    return {
        hash: sha256(COMPILER_VERSION + '\n' + candidates.join('\n')),
        candidates,
        covers: Object.keys(covers).sort(),
        builds,
    };
}

function descriptor(releaseId: string, hash: string, covers: string[]): PortalUtilities {
    return { css: assetUrl(releaseId, PORTAL_UTILITIES_ASSET, hash.substring(0, 16)), hash, covers };
}

/** Portals whose sheet compile is queued in this script: portal sys_id → union hash. */
const queued: Record<string, string> = {};

/**
 * Queued compiles run one after another. Started together they interleave (Tailwind's compile() is
 * asynchronous), so a reprocess of every portal measured each compile as the whole burst.
 */
let compileChain: Promise<unknown> = Promise.resolve();

/**
 * The utilities descriptor for a manifest about to be written to `release` (null when the portal has
 * no release yet). Queues a compile when the union changed; `reprocess` runs after the sheet is saved.
 */
export function utilitiesFor(
    portalId: string,
    release: GR | null,
    plan: UtilitiesPlan,
    reprocess: (portalId: string) => void
): PortalUtilities | null {
    const current = release ? str(release, 'utilities_hash') : '';
    if (release && current && current === plan.hash) return descriptor(release.getUniqueValue(), current, plan.covers);

    queueCompile(portalId, plan, reprocess);
    if (!release || !current) return null;
    // Keep the previous sheet for the builds it already covers (same key = same utilities).
    const previous = parseJson<{ utilities?: PortalUtilities | null }>(str(release, 'manifest_json'), {});
    const before: Record<string, boolean> = {};
    const old = previous && previous.utilities;
    if (!old || old.hash !== current) return null;
    for (const k of old.covers || []) before[k] = true;
    return descriptor(
        release.getUniqueValue(),
        current,
        plan.covers.filter((k) => before[k])
    );
}

function queueCompile(portalId: string, plan: UtilitiesPlan, reprocess: (portalId: string) => void): void {
    if (queued[portalId] === plan.hash) return;
    queued[portalId] = plan.hash;
    // Settles at the end of the outermost script (the instance's Promise semantics), like the
    // compile-on-save of a component; the save, seed or reprocess request waits for it.
    compileChain = compileChain
        .then(() => {
            if (queued[portalId] !== plan.hash) return null; // a newer union was queued meanwhile
            const started = Date.now();
            return compilePortalUtilities(plan.candidates).then((css) => {
                if (queued[portalId] !== plan.hash) return;
                const ms = Date.now() - started;
                const release = findOne(T.release, `portal=${portalId}`);
                if (!release) return;
                const r = getById(T.release, release.getUniqueValue());
                r.setValue('utilities_css', css);
                r.setValue('utilities_hash', plan.hash);
                r.setValue(
                    'utilities_meta',
                    JSON.stringify({
                        candidates: plan.candidates.length,
                        hostCandidates: HOST_CANDIDATES.length,
                        builds: plan.builds,
                        bytes: css.length,
                        ms,
                        compiler: COMPILER_VERSION,
                        compiledAt: nowValue(),
                    })
                );
                r.update();
                delete queued[portalId];
                gs.info(
                    `[rp] portal utilities ${portalId}: ${plan.candidates.length} candidates, ${plan.builds} builds, ${css.length} bytes, ${ms} ms`
                );
                reprocess(portalId);
            });
        })
        .then(null, (e: unknown) => {
            delete queued[portalId];
            gs.error(`[rp] portal utilities ${portalId} failed: ${String((e && (e as Error).message) || e)}`);
        });
}

/** The sheet's content for the asset API, or null when the release has none. */
export function portalUtilitiesCss(releaseId: string): { release: GR; css: string; hash: string } | null {
    const r = getById(T.release, releaseId);
    if (!r) return null;
    const hash = str(r, 'utilities_hash');
    if (!hash) return null;
    return { release: r, css: str(r, 'utilities_css'), hash };
}
