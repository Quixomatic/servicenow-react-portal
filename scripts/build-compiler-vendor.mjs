// Bundles the server-side compiler libraries into self-contained ES modules under
// src/server/compiler/vendor/, which the Fluent SDK installs as server modules (sys_module).
// Run after upgrading sucrase or tailwindcss:  npm run vendor:compiler
import { build } from 'esbuild';
import { writeFileSync, readFileSync, readdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { createProgress } from './lib/progress.mjs';

const out = 'src/server/compiler/vendor';
const common = {
    bundle: true,
    format: 'esm',
    target: 'es2019',
    platform: 'neutral',
    mainFields: ['module', 'main'],
    minify: true,
    legalComments: 'eof',
    write: false,
    logLevel: 'warning',
};

// Spinner per bundle (scripts/lib/progress.mjs; --progress=tty|lines|off, --quiet).
const P = createProgress();

async function bundle(name, contents, extra = {}) {
    const task = P.mode === 'off' ? null : P.task(`bundling ${name}.js`);
    const result = await build({ ...common, ...extra, stdin: { contents, resolveDir: process.cwd(), loader: 'js' } });
    const header = `// @ts-nocheck\n/* eslint-disable */\n// Generated by scripts/build-compiler-vendor.mjs — do not edit.\n`;
    writeFileSync(`${out}/${name}.js`, header + result.outputFiles[0].text);
    const size = `${(result.outputFiles[0].text.length / 1024).toFixed(0)} KB`;
    if (task) task.succeed(`${out}/${name}.js ${size}`);
    else P.log(`${name}.js ${size}`);
}

const pkg = (p) => JSON.parse(readFileSync(`node_modules/${p}/package.json`, 'utf8')).version;

await bundle(
    'sucrase',
    `export { transform } from 'sucrase'\nexport const version = ${JSON.stringify(pkg('sucrase'))}`
);
// The portal utilities sheet (one per portal) also compiles the host's classes, so its input adds the
// two CSS packages the host's framework CSS imports (packages/portal-host/src/styles/tailwind.css).
const HOST_MODULES = './packages/portal-host/node_modules';
const hostPkg = (p) => JSON.parse(readFileSync(`${HOST_MODULES}/${p}/package.json`, 'utf8')).version;

await bundle(
    'tailwind',
    `export { compile, __unstable__loadDesignSystem as loadDesignSystem } from 'tailwindcss'
import theme from 'tailwindcss/theme.css'
import preflight from 'tailwindcss/preflight.css'
import utilities from 'tailwindcss/utilities.css'
import index from 'tailwindcss/index.css'
import twAnimate from '${HOST_MODULES}/tw-animate-css/dist/tw-animate.css'
import shadcn from '${HOST_MODULES}/shadcn/dist/tailwind.css'
export const sheets = { 'tailwindcss': index, 'tailwindcss/theme': theme, 'tailwindcss/preflight': preflight, 'tailwindcss/utilities': utilities, 'tw-animate-css': twAnimate, 'shadcn/tailwind.css': shadcn }
export const version = ${JSON.stringify(pkg('tailwindcss'))}
export const hostCssVersions = ${JSON.stringify({ 'tw-animate-css': hostPkg('tw-animate-css'), shadcn: hostPkg('shadcn') })}`,
    { loader: { '.css': 'text' } }
);

// Utility roots (src/server/compiler/utility-roots.ts): the design system's utility names for the portal
// input. The compiler's root pre-filter (isPossibleUtility) drops every extracted word that can't start
// with one, before Tailwind's candidatesToCss. Generated from the bundle just written, then checked: a
// valid class the filter would drop FAILS the run (it would vanish from a build's utilities).
const ROOTS_FILE = 'src/server/compiler/utility-roots.ts';
const rootsTask = P.mode === 'off' ? null : P.task('utility roots');
const vendorUrl = (f) => pathToFileURL(`${process.cwd()}/${out}/${f}`).href + `?t=${Date.now()}`;
const tw = await import(vendorUrl('tailwind.js'));
// The compiler module (Node strips the types); only its inputs and filter are used here.
const compiler = await import(pathToFileURL(`${process.cwd()}/src/server/compiler/compiler.ts`).href);
const twOptions = {
    base: '/',
    loadStylesheet: (id, base) => Promise.resolve({ content: tw.sheets[id], base, path: id }),
};
const ds = await tw.loadDesignSystem(compiler.PORTAL_TAILWIND_INPUT, twOptions);
const rootNames = [...new Set([...ds.utilities.keys('static'), ...ds.utilities.keys('functional')])].sort();
const rootsKey = createHash('sha256').update(rootNames.join('\n')).digest('hex').substring(0, 16);
const rootSet = {};
for (const r of rootNames) rootSet[r] = true;
const unquotable = rootNames.filter((r) => /['"\\]/.test(r));
if (unquotable.length) throw new Error(`Utility roots with quotes or backslashes: ${unquotable.join(', ')}`);

// Soundness: every valid class (the design system's class list under common variant forms, every class
// in the seed components, the host's classes) must pass the filter; the host's classes must all be valid.
const VARIANTS = [
    '',
    'hover:',
    'md:',
    'dark:',
    'group-hover/item:',
    'data-[state=open]:',
    '[&>svg]:',
    '*:',
    'max-sm:',
    '@md:',
    'aria-[x=y]:',
    'supports-[display:grid]:',
    'not-first:',
    'has-[>img]:',
    'peer-checked/name:',
    '!',
];
const words = new Set();
for (const [name] of ds.getClassList()) for (const v of VARIANTS) words.add(v === '!' ? '!' + name : v + name);
const seedDir = 'scripts/seed/components';
const seedSources = [];
const walk = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
        const p = `${dir}/${e.name}`;
        if (e.isDirectory()) walk(p);
        else if (/\.(tsx|ts|jsx|js|mjs|css)$/.test(e.name)) seedSources.push(readFileSync(p, 'utf8'));
    }
};
if (existsSync(seedDir)) walk(seedDir);
for (const w of compiler.extractCandidates(seedSources)) words.add(w);
const { HOST_CANDIDATES } = await import(pathToFileURL(`${process.cwd()}/src/server/compiler/host-candidates.ts`).href);
for (const c of HOST_CANDIDATES) words.add(c);
const list = [...words];
const css = ds.candidatesToCss(list);
const dropped = list.filter(
    (w, i) => css[i] !== null && css[i] !== undefined && !compiler.isPossibleUtility(w, rootSet)
);
const hostInvalid = HOST_CANDIDATES.filter((c) => {
    const r = ds.candidatesToCss([c])[0];
    return r === null || r === undefined;
});
if (dropped.length || hostInvalid.length) {
    if (rootsTask) rootsTask.fail('unsound');
    if (dropped.length)
        console.error(
            `The root pre-filter would drop ${dropped.length} valid classes:\n  ${dropped.slice(0, 50).join('\n  ')}`
        );
    if (hostInvalid.length)
        console.error(`Host classes the portal input rejects:\n  ${hostInvalid.slice(0, 50).join('\n  ')}`);
    console.error(
        'Fix isPossibleUtility in src/server/compiler/compiler.ts (or host-candidates.ts) before installing.'
    );
    process.exit(1);
}
writeFileSync(
    ROOTS_FILE,
    [
        '// Generated by scripts/build-compiler-vendor.mjs — do not edit.',
        "// Tailwind's utility roots for the portal input (PORTAL_TAILWIND_INPUT): the compiler's root pre-filter.",
        '/* eslint-disable */',
        `export const UTILITY_ROOTS_KEY = '${rootsKey}';`,
        '',
        'export const UTILITY_ROOTS: string[] = [',
        ...rootNames.map((r) => `    ${JSON.stringify(r).replace(/^"|"$/g, "'")},`),
        '];',
        '',
    ].join('\n')
);
const note = `${rootNames.length} roots, key ${rootsKey}, ${list.length} classes checked`;
if (rootsTask) rootsTask.succeed(note);
else P.log(`utility roots: ${note}`);
