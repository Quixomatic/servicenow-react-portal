/**
 * React Portal docs seed (idempotent): the docs collection `react-portal` (created when missing, never
 * updated: its title, description and icon are instance-owned), its sections (by slug, from
 * docs/guide/_nav.json) and its pages (by path). Pages and sections that left docs/guide/ are
 * deactivated (never deleted). Rows edited in Studio are filtered out by run-seed.mjs (classifyDocs /
 * classifySections in docs-lib.mjs), never here. Only the react-portal collection is touched.
 *
 * Migration (pre-collection rows): SECTIONS.link sets doc_section on pages that have none (their
 * collection follows through "RP: Doc page collection from section"); no content or hash changes.
 *
 * GENERATED by scripts/seed/run-seed.mjs (the docs step of `npm run seed`) from docs/guide/; don't
 * edit the generated copy. Logs "[seed] done (docs) run=<id>: …" (or "[seed] failed run=<id>").
 */
(function () {
    var SEED_RUN_ID = '__SEED_RUN_ID__';
    var DOCS = __DOCS_JSON__;
    var DEACTIVATE = __DOCS_DEACTIVATE__;
    // [{ path, seed_hash }]: content already matches the repo (e.g. a pulled Studio edit); stamp only.
    var ADOPT = __DOCS_ADOPT__;
    // { key, title, description, icon }
    var COLLECTION = __DOCS_COLLECTION__;
    // { write: [row], adopt: [{ slug, seed_hash }], deactivate: [slug], create: [row], link: [{ id, slug }] }
    var SECTIONS = __DOCS_SECTIONS__;
    var T = 'x_312987_portal_doc';
    var TS = 'x_312987_portal_doc_section';
    var TC = 'x_312987_portal_doc_collection';
    var t0 = Date.now();
    var written = 0;
    var created = 0;
    var deactivated = 0;
    var adopted = 0;
    var secWritten = 0;
    var secAdopted = 0;
    var secDeactivated = 0;
    var linked = 0;
    function setAll(gr, row) {
        for (var k in row) {
            var v = row[k];
            gr.setValue(k, v === null || v === undefined ? '' : typeof v === 'object' ? JSON.stringify(v) : String(v));
        }
    }
    function findSection(colId, slug) {
        var s = new GlideRecord(TS);
        s.addQuery('collection', colId);
        s.addQuery('slug', slug);
        s.setLimit(1);
        s.query();
        return s.next() ? s : null;
    }
    // The collection's pages, plus rows that have no collection yet (they belong to react-portal).
    function findPage(colId, path) {
        var p = new GlideRecord(T);
        p.addEncodedQuery('path=' + path + '^collection=' + colId + '^ORcollectionISEMPTY');
        p.setLimit(1);
        p.query();
        return p.next() ? p : null;
    }
    try {
        // 1. The collection (created once).
        var col = new GlideRecord(TC);
        col.addQuery('key', COLLECTION.key);
        col.setLimit(1);
        col.query();
        var colId;
        if (col.next()) colId = col.getUniqueValue();
        else {
            col.initialize();
            setAll(col, {
                key: COLLECTION.key,
                title: COLLECTION.title || COLLECTION.key,
                description: COLLECTION.description || '',
                icon: COLLECTION.icon || '',
                active: true,
            });
            colId = col.insert();
            if (!colId)
                throw new Error('Could not create doc collection ' + COLLECTION.key + ': ' + gs.getErrorMessages());
        }
        // 2. Sections: repo writes, Studio-only sections the migration needs, adopts, deactivations.
        var all = SECTIONS.write.concat(SECTIONS.create);
        for (var si = 0; si < all.length; si++) {
            var row = all[si];
            var sec = findSection(colId, row.slug);
            var isNewSec = !sec;
            if (isNewSec) {
                sec = new GlideRecord(TS);
                sec.initialize();
                sec.setValue('collection', colId);
            } else if (si >= SECTIONS.write.length) continue; // create: only when missing
            setAll(sec, row);
            var sid = isNewSec ? sec.insert() : (sec.update(), sec.getUniqueValue());
            if (!sid) throw new Error('Could not write doc section ' + row.slug + ': ' + gs.getErrorMessages());
            secWritten++;
        }
        for (var sa = 0; sa < SECTIONS.adopt.length; sa++) {
            var ads = findSection(colId, SECTIONS.adopt[sa].slug);
            if (!ads) continue;
            ads.setValue('seed_hash', SECTIONS.adopt[sa].seed_hash);
            ads.setValue('origin', 'repo');
            ads.update();
            secAdopted++;
        }
        for (var sd = 0; sd < SECTIONS.deactivate.length; sd++) {
            var ds = findSection(colId, SECTIONS.deactivate[sd]);
            if (!ds || ds.getValue('active') !== '1') continue;
            ds.setValue('active', false);
            ds.update();
            secDeactivated++;
        }
        var sectionIds = {};
        var sl = new GlideRecord(TS);
        sl.addQuery('collection', colId);
        sl.query();
        while (sl.next()) sectionIds[sl.getValue('slug')] = sl.getUniqueValue();
        // 3. Migration: pages without a section reference (content untouched).
        for (var li = 0; li < SECTIONS.link.length; li++) {
            var lk = new GlideRecord(T);
            if (!lk.get(SECTIONS.link[li].id) || lk.getValue('doc_section')) continue;
            var target = sectionIds[SECTIONS.link[li].slug];
            if (!target) continue;
            lk.setValue('doc_section', target);
            lk.update();
            linked++;
        }
        // 4. Pages.
        for (var i = 0; i < DOCS.length; i++) {
            var d = DOCS[i];
            var gr = findPage(colId, d.path);
            var isNew = !gr;
            if (isNew) {
                gr = new GlideRecord(T);
                gr.initialize();
            }
            setAll(gr, d);
            if (sectionIds[d.section_slug]) gr.setValue('doc_section', sectionIds[d.section_slug]);
            var id = isNew ? gr.insert() : (gr.update(), gr.getUniqueValue());
            if (!id) throw new Error('Could not write doc ' + d.path + ': ' + gs.getErrorMessages());
            written++;
            if (isNew) created++;
        }
        for (var j = 0; j < DEACTIVATE.length; j++) {
            var old = findPage(colId, DEACTIVATE[j]);
            if (!old || old.getValue('active') !== '1') continue;
            old.setValue('active', false);
            old.update();
            deactivated++;
        }
        for (var a = 0; a < ADOPT.length; a++) {
            var ad = findPage(colId, ADOPT[a].path);
            if (!ad) continue;
            ad.setValue('seed_hash', ADOPT[a].seed_hash);
            ad.setValue('origin', 'repo');
            ad.update();
            adopted++;
        }
        gs.info(
            '[seed] done (docs) run=' +
                SEED_RUN_ID +
                ': ' +
                written +
                ' docs written (' +
                created +
                ' new), ' +
                adopted +
                ' adopted, ' +
                deactivated +
                ' deactivated; sections ' +
                secWritten +
                ' written, ' +
                secAdopted +
                ' adopted, ' +
                secDeactivated +
                ' deactivated; ' +
                linked +
                ' linked |  | docs ' +
                (Date.now() - t0) +
                'ms'
        );
    } catch (e) {
        gs.error('[seed] failed run=' + SEED_RUN_ID + ': ' + e);
        throw e;
    }
})();
