/** What an activity entry is about (from its event table). */
export type ActivityKind = 'journal' | 'audit' | 'attachment' | 'email' | 'relation' | 'other';

/** An author, from the stream's userReferences (keyed by user_name in events). */
export type ActivityUser = {
    sysId: string;
    userName: string;
    displayName: string;
    initials: string;
    /** Avatar image path ('' when the user has none). */
    avatar: string;
    email: string;
    active: boolean;
    identityType?: string;
};

/** One field change of an audit entry (display values, as the platform renders them). */
export type ActivityChange = {
    field: string;
    label: string;
    /** null on the record's creation entry (no previous value). */
    oldValue: string | null;
    newValue: string;
    /** Dictionary type (integer, reference, …). */
    type: string;
};

export type ActivityAttachment = {
    sysId: string;
    fileName: string;
    contentType: string;
    sizeBytes: number;
    tableName: string;
    /** The attachment was deleted (entries can outlive their file). */
    removed: boolean;
};

export type ActivityEmail = {
    subject: string;
    from: string;
    to: string[];
    cc: string[];
    /** 'sent' | 'received' | … */
    type: string;
};

/** One normalised activity stream entry (GlideActivity getEvents event). */
export type ActivityEntry = {
    /** Stable key: `${eventTable}:${eventSysId}`. */
    key: string;
    kind: ActivityKind;
    eventTable: string;
    eventSysId: string;
    documentTable: string;
    documentId: string;
    /** Epoch ms. */
    createdAt: number;
    /** In the user's format and time zone. */
    createdAtDisplay: string;
    /** Glide UTC value. */
    createdAtValue: string;
    /** user_name of the author. */
    createdBy: string;
    author: ActivityUser;
    /** Journal: the field name; attachment: the content type; email: autogenerated / correspondence. */
    subtype: string;
    /** The platform's title ('Work notes', 'Field changes', 'Image', …). */
    title: string;
    /** Journal entries. */
    field?: string;
    /** Journal content as the server sends it (HTML-escaped text or sanitised HTML): render sanitised. */
    content?: string;
    /** The server sent only the beginning (see fetchFullJournalEntry). */
    truncated?: boolean;
    /** Audit entries. */
    changes?: ActivityChange[];
    /** Audit: the record's creation (values without previous ones). */
    initial?: boolean;
    attachment?: ActivityAttachment;
    email?: ActivityEmail;
    /** The raw parsed payload. */
    payload: Record<string, any>;
};

/** The platform's activity filter configuration for the table (sys_activity filters + formatter fields). */
export type ActivityFilterField = {
    /** Field name, or a special filter: '*Attachments*', '*EmailAutogenerated*', '*Relations*', … */
    name: string;
    label: string;
    journal: boolean;
    /** Selected by default. */
    selected: boolean;
    special: boolean;
    /** Which entries it governs: the document table (field changes), sys_journal_field, sys_attachment, sys_email… */
    eventTable: string;
    subtype: string;
};

export type ActivityData = {
    table: string;
    sysId: string;
    /** Newest first. */
    entries: ActivityEntry[];
    filterFields: ActivityFilterField[];
    /** By user_name. */
    users: Record<string, ActivityUser>;
    /** The stream's own AMB channels (/activity/events/<sys_id>, /activity/supplemental/…). */
    ambChannels: string[];
    featureFlags: { name: string; value: unknown }[];
    /** Background colours per journal subtype from the platform's supplemental config (work_notes → 'yellow'). */
    subtypeColors: Record<string, string>;
};

/** Which entries to show. Omitted keys show everything. */
export type ActivityFilters = {
    kinds?: ActivityKind[];
    /** Journal fields to show (work_notes, comments, …). */
    journalFields?: string[];
    /** Audited fields to show in field changes. */
    fields?: string[];
    /** Free-text match on content, field changes, file names, subjects and authors. */
    search?: string;
};

/** A journal field the composer can post to. */
export type JournalFieldInfo = {
    name: string;
    label: string;
    /** The user may write it (field ACL + dictionary). */
    writable: boolean;
    maxLength?: number;
    /** Internal-only notes (work notes). */
    internal: boolean;
    /** Platform help text ('Only internal users can see work notes'). */
    help: string;
};
