#!/usr/bin/env node
// Generates the server-side lucide icon modules from packages/portal-host/node_modules/lucide-react:
//
//   src/server/icons/lucide-names.ts   icon names (kebab-case), for validation and the studio picker
//   src/server/icons/lucide-sprite.ts  inner SVG markup per icon, for the classic-form icon picker
//
// Run after upgrading lucide-react in the host:  node scripts/generate-lucide-icons.mjs
//
// Both modules hold their data as string literals of at most ~30 KB each (Rhino caps a compiled
// string constant at 64 KB), joined/split at load time.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = join(root, 'packages', 'portal-host', 'node_modules', 'lucide-react');
const iconsDir = join(pkgDir, 'dist', 'esm', 'icons');
const outDir = join(root, 'src', 'server', 'icons');
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;

const NAME_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const icons = {};
const aliases = {};

for (const file of readdirSync(iconsDir).sort()) {
    if (!file.endsWith('.mjs')) continue;
    const src = readFileSync(join(iconsDir, file), 'utf8');
    // Alias files only re-export another icon; aliases are listed on the canonical icon.
    const dataMatch = src.match(/const __iconData = (\{[\s\S]*?\n\});/);
    if (!dataMatch) continue;
    // The literal is plain data ({ name, node: [tag, attrs][], aliases? }): evaluate it as an expression.
    const data = new Function('return ' + dataMatch[1])();
    const name = data.name;
    if (!NAME_RE.test(name)) continue;
    const node = data.node;
    for (const a of data.aliases || []) if (NAME_RE.test(a)) aliases[a] = name;
    const markup = node
        .map(([tag, attrs]) => {
            const parts = Object.keys(attrs)
                .filter((k) => k !== 'key')
                .map((k) => `${k}='${String(attrs[k]).replace(/'/g, '&#39;')}'`);
            return `<${tag} ${parts.join(' ')}/>`;
        })
        .join('');
    icons[name] = markup;
}

const names = Object.keys(icons).sort();
const allNames = names.concat(Object.keys(aliases).filter((a) => !icons[a])).sort();
if (names.length < 1000) throw new Error(`Only ${names.length} icons found in ${iconsDir}`);

function chunk(text, size) {
    const out = [];
    for (let i = 0; i < text.length; i += size) out.push(text.slice(i, i + size));
    return out;
}

const header = (what) =>
    `/* eslint-disable */\n// GENERATED by scripts/generate-lucide-icons.mjs from lucide-react ${version} (ISC license). Do not edit.\n// ${what}\n`;

mkdirSync(outDir, { recursive: true });

const namesText = allNames.join(' ');
writeFileSync(
    join(outDir, 'lucide-names.ts'),
    header(`${allNames.length} icon names (kebab-case), ${names.length} icons plus their aliases.`) +
        `\nexport const LUCIDE_VERSION = '${version}'\n\n` +
        `const CHUNKS: string[] = [\n${chunk(namesText, 30000)
            .map((c) => `    ${JSON.stringify(c)},`)
            .join('\n')}\n]\n\n` +
        `/** Every lucide icon name (aliases included), sorted. */\nexport const LUCIDE_ICON_NAMES: string[] = CHUNKS.join('').split(' ')\n`
);

const spriteJson = JSON.stringify({ version, icons, aliases });
writeFileSync(
    join(outDir, 'lucide-sprite.ts'),
    header(
        `Inner SVG markup for ${names.length} icons (24x24 viewBox, stroke icons), as JSON { version, icons: { name: markup }, aliases: { alias: name } }.`
    ) +
        `\nconst CHUNKS: string[] = [\n${chunk(spriteJson, 30000)
            .map((c) => `    ${JSON.stringify(c)},`)
            .join('\n')}\n]\n\n` +
        `/** The sprite as JSON text (served as-is by the runtime API). */\nexport function lucideSpriteJson(): string {\n    return CHUNKS.join('')\n}\n`
);

console.log(
    `lucide-react ${version}: ${names.length} icons, ${allNames.length} names; names ${namesText.length} chars, sprite ${spriteJson.length} chars`
);
