const iconNames = Object.keys(icons)

function keyOf(name) {
  return String(name || "")
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Za-z])([0-9])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase()
}

/** The lucide component for a name, or null. */
function getIcon(name) {
  if (!name) return null
  return icons[keyOf(name)] || icons[String(name).toLowerCase()] || null
}

/** <Icon name="inbox" className? size? />: decorative by default (aria-hidden) unless `label` is given. */
function Icon({ name, label, fallback = true, ...props }) {
  const Component = getIcon(name) || (fallback ? Circle : null)
  if (!Component) return null
  const a11y = label ? { role: "img", "aria-label": label } : { "aria-hidden": true }
  return <Component data-icon={keyOf(name) || "circle"} {...a11y} {...props} />
}

export { Icon, getIcon, icons, iconNames }
