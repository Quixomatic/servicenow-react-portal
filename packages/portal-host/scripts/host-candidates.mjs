// Generates src/server/compiler/host-candidates.ts: the host's Tailwind classes, which the server adds to
// every portal utilities sheet (one Tailwind sheet per portal, in @layer rp-portal, above the framework
// CSS). Runs after build:css, from the same input (src/styles/tailwind.css) and the same sources.
//
// The host must never lose its styles: the framework CSS stays injected as it is, and the portal sheet
// re-emits the host's classes after it, in Tailwind's own order. That is only safe when the portal
// sheet emits each host class exactly like the framework CSS does, so every class is compiled with both
// inputs (the host's and the server's PORTAL_TAILWIND_INPUT, from the vendored Tailwind the instance
// runs) and compared. Any difference FAILS the build with the list.
//
// The one accepted difference: the server's dark variant also matches `.dark` / `.dark *` (Studio
// previews), a superset of the host's `:host(.dark)` / `:host(.dark) *`.
//
// Usage: node scripts/host-candidates.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile, __unstable__loadDesignSystem as loadHostDesignSystem } from '@tailwindcss/node';
import { Scanner } from '@tailwindcss/oxide';
import { PORTAL_TAILWIND_INPUT } from '../../../src/server/compiler/compiler.ts';
import { loadDesignSystem, sheets } from '../../../src/server/compiler/vendor/tailwind.js';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const input = join(pkg, 'src/styles/tailwind.css');
const out = resolve(pkg, '../../src/server/compiler/host-candidates.ts');
const css = readFileSync(input, 'utf8');
const base = dirname(input);

// 1. The host's candidates: the same sources the Tailwind CLI scans for build:css (@source rules, plus
//    automatic detection from the package root, which is where pnpm build:css runs).
const compiler = await compile(css, { base, onDependency: () => {} });
const sources = [];
if (compiler.root === null) sources.push({ base: pkg, pattern: '**/*', negated: false });
else if (compiler.root && compiler.root !== 'none')
    sources.push({ base: compiler.root.base, pattern: compiler.root.pattern, negated: false });
for (const s of compiler.sources) sources.push(s);
const scanned = new Scanner({ sources }).scan();

// 2. Utilities by the host's input.
const host = await loadHostDesignSystem(css, { base });
const hostCss = host.candidatesToCss(scanned);
const candidates = [];
const hostRules = [];
scanned.forEach((c, i) => {
    if (hostCss[i] === null || hostCss[i] === undefined) return;
    candidates.push(c);
    hostRules.push(hostCss[i]);
});

// 3. The same classes by the server's portal input.
const portal = await loadDesignSystem(PORTAL_TAILWIND_INPUT, {
    base: '/',
    loadStylesheet: async (id, b) => {
        if (sheets[id] === undefined) throw new Error(`Unknown stylesheet ${id}`);
        return { content: sheets[id], base: b, path: id };
    },
});
const portalCss = portal.candidatesToCss(candidates);

const SERVER_DARK = ':where(:host(.dark), :host(.dark) *, .dark, .dark *)';
const HOST_DARK = ':where(:host(.dark), :host(.dark) *)';
const normalize = (text) => String(text).split(SERVER_DARK).join(HOST_DARK).replace(/\s+/g, ' ').trim();

const differ = [];
candidates.forEach((c, i) => {
    if (portalCss[i] === null || portalCss[i] === undefined) differ.push({ c, why: 'not a utility on the server' });
    else if (normalize(portalCss[i]) !== normalize(hostRules[i])) differ.push({ c, why: 'different CSS' });
});
if (differ.length) {
    console.error(`host-candidates: ${differ.length} host class(es) compile differently on the server:`);
    for (const d of differ.slice(0, 200)) {
        console.error(`  ${d.c}: ${d.why}`);
        if (process.env.HOST_CANDIDATES_VERBOSE) {
            const i = candidates.indexOf(d.c);
            console.error(`    host:   ${normalize(hostRules[i])}`);
            console.error(`    server: ${portalCss[i] === null ? 'null' : normalize(portalCss[i])}`);
        }
    }
    console.error(
        'Align src/server/compiler/compiler.ts (tailwindInput) with src/styles/tailwind.css, or change the class.'
    );
    process.exit(1);
}

candidates.sort();
const body = [
    '// Generated by packages/portal-host/scripts/host-candidates.mjs (pnpm build:css) — do not edit.',
    "// The host's Tailwind classes, verified to compile identically with the server's portal input.",
    '// Every portal utilities sheet includes them (release/portal-utilities.ts).',
    '/* eslint-disable */',
    'export const HOST_CANDIDATES: string[] = [',
    ...candidates.map((c) => `    ${JSON.stringify(c)},`),
    '];',
    '',
].join('\n');
let previous = '';
try {
    previous = readFileSync(out, 'utf8');
} catch (e) {
    previous = '';
}
if (previous !== body) writeFileSync(out, body);
console.log(
    `host-candidates: ${candidates.length} host classes (${scanned.length} scanned) ${previous === body ? 'unchanged' : 'written'}`
);
